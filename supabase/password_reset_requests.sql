create table if not exists public.password_reset_requests (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_directory(id) on delete cascade,
  uid text not null,
  user_name text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  temporary_password text,
  created_at timestamptz not null default now(),
  approved_at timestamptz
);

create index if not exists password_reset_requests_status_idx on public.password_reset_requests(status, created_at desc);
create unique index if not exists password_reset_requests_one_pending_per_user_idx
  on public.password_reset_requests(user_id) where status = 'pending';
alter table public.password_reset_requests enable row level security;

drop policy if exists "Users can request password reset" on public.password_reset_requests;
create policy "Users can request password reset"
on public.password_reset_requests for insert to anon, authenticated
with check (status = 'pending');

drop policy if exists "Admins can read password reset requests" on public.password_reset_requests;
create policy "Admins can read password reset requests"
on public.password_reset_requests for select to authenticated
using (public.is_directory_admin());

drop policy if exists "Admins can approve password reset requests" on public.password_reset_requests;
create policy "Admins can approve password reset requests"
on public.password_reset_requests for update to authenticated
using (public.is_directory_admin())
with check (public.is_directory_admin());
