create table if not exists public.borrow_records (
  id bigint generated by default as identity primary key,
  date text not null,
  plate text not null,
  model text not null,
  car_id bigint references public.cars(id) on delete set null,
  vehicle_id bigint references public.cars(id) on delete set null,
  requester text not null,
  requester_uid text,
  user_id bigint,
  purpose text not null,
  mileage text not null,
  start_mileage text,
  end_mileage text not null default '-',
  return_date text not null,
  distance text not null default '-',
  status text not null check (status in ('in-use', 'reserved', 'returned', 'cancelled')),
  created_at timestamptz not null default now()
);

