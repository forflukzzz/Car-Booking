create policy "Public can read borrow records"
on public.borrow_records for select to anon, authenticated using (true);

-- Anonymous clients may submit new reservation requests only. They cannot
-- insert arbitrary statuses or blank booking details, and receive no UPDATE/DELETE access.
create policy "Public can submit borrow requests"
on public.borrow_records for insert to anon, authenticated
with check (
  status in ('reserved', 'in-use')
  and length(btrim(requester)) between 1 and 200
  and length(btrim(date)) > 0
  and length(btrim(return_date)) > 0
  and length(btrim(plate)) > 0
  and length(btrim(model)) > 0
  and length(btrim(purpose)) between 1 and 2000
);

create policy "Public can update borrow requests"
on public.borrow_records for update to anon, authenticated
using (true)
with check (true);

