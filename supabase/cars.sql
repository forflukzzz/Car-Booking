create or replace function public.sync_car_mileage_from_service_record()
returns trigger
language plpgsql
as $$
begin
  update public.cars
  set mileage = new.mileage
  where id = new.car_id
    and nullif(trim(new.mileage), '') is not null;
  return new;
end;
$$;

drop trigger if exists sync_car_mileage_from_service_record on public.car_service_records;
create trigger sync_car_mileage_from_service_record
after insert or update of mileage, car_id on public.car_service_records
for each row execute function public.sync_car_mileage_from_service_record();

