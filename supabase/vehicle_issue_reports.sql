create table if not exists public.vehicle_issue_reports (
  id bigint generated by default as identity primary key,
  borrow_record_id bigint not null references public.borrow_records(id) on delete cascade,
  car_id bigint references public.cars(id) on delete set null,
  plate text not null,
  model text not null,
  requester text not null,
  issue_description text not null check (length(btrim(issue_description)) between 1 and 2000),
  reported_at timestamptz not null default now()
);

create index if not exists vehicle_issue_reports_borrow_record_id_idx
  on public.vehicle_issue_reports (borrow_record_id);

create index if not exists vehicle_issue_reports_reported_at_idx
  on public.vehicle_issue_reports (reported_at desc);

alter table public.vehicle_issue_reports enable row level security;

grant select, insert on public.vehicle_issue_reports to anon, authenticated;
grant usage, select on sequence public.vehicle_issue_reports_id_seq to anon, authenticated;

drop policy if exists "Public can read vehicle issue reports" on public.vehicle_issue_reports;
drop policy if exists "Public can submit vehicle issue reports" on public.vehicle_issue_reports;

create policy "Public can read vehicle issue reports"
on public.vehicle_issue_reports for select to anon, authenticated
using (true);

create policy "Public can submit vehicle issue reports"
on public.vehicle_issue_reports for insert to anon, authenticated
with check (
  length(btrim(plate)) > 0
  and length(btrim(model)) > 0
  and length(btrim(requester)) > 0
  and length(btrim(issue_description)) between 1 and 2000
);

notify pgrst, 'reload schema';
